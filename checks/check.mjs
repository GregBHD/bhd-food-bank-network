assert.equal(read('orderTarget(order("O-3101"),"delivery")'),650);
assert.equal(read('orderGap(order("O-3101"),"food")'),2700);
assert.equal(read('fundingLeaders()[0].name'),'Northline Manufacturing');
assert.equal(read('fundingLeaders()[0].score'),2700);
assert.equal(read('fundingLeaders().reduce((n,r)=>n+r.score,0)'),5220);
assert.equal(read('fundingLeaders("food").reduce((n,r)=>n+r.score,0)'),1700);
assert.throws(()=>read('addOrderPledge("O-3101","Test",2700,651)'),/remaining amount/);
assert.equal(read('order("O-3101").pledges.length'),2,'Failed mixed pledge must not mutate either ledger');
assert.throws(()=>read('addOrderPledge("O-3101","Test",-1,50)'),/positive/);
assert.throws(()=>read('addOrderPledge("O-3102","Test",0,1)'),/remaining amount/);
read('const orderTestPledge=addOrderPledge("O-3101","Test sponsor",2700,650)');
